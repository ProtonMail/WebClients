/**
 * Generates src/app/util/slides/arialMetrics.generated.ts: advance widths (in em) for the
 * characters slide text is measured with. Run with Node from the repo after installing
 * LibreOffice, which ships Liberation Sans:
 *
 *   node applications/lumo/dev/slides/generateArialMetrics.cjs
 *
 * Liberation Sans is metric-compatible with Arial (same advance widths; checked 2026-10-15
 * against macOS Arial for all 584 code points below), and it is licensed under the SIL OFL,
 * so the widths can be committed. The .pptx names Arial; PowerPoint, Keynote and Google
 * Slides have it, and LibreOffice substitutes Liberation Sans.
 */
const fs = require('fs');
const path = require('path');
const fontkit = require('fontkit');

const FONT_DIR = '/Applications/LibreOffice.app/Contents/Resources/fonts/truetype';
const OUT = path.join(__dirname, '../../src/app/util/slides/arialMetrics.generated.ts');
const RANGES = [
    [0x20, 0x24f],
    [0x2000, 0x206f],
    [0x20ac, 0x20ac],
    [0x2122, 0x2122],
];

const widthsFor = (file) => {
    const font = fontkit.openSync(path.join(FONT_DIR, file));
    const entries = [];
    for (const [start, end] of RANGES) {
        for (let cp = start; cp <= end; cp++) {
            if (font.hasGlyphForCodePoint(cp)) {
                entries.push(`${cp}:${font.glyphForCodePoint(cp).advanceWidth}`);
            }
        }
    }
    return { unitsPerEm: font.unitsPerEm, entries };
};

const regular = widthsFor('LiberationSans-Regular.ttf');
const bold = widthsFor('LiberationSans-Bold.ttf');

const source = `// Generated by applications/lumo/dev/slides/generateArialMetrics.cjs. Do not edit.
// Advance widths of Liberation Sans (metric-compatible with Arial), in font units.

export const ARIAL_UNITS_PER_EM = ${regular.unitsPerEm};

export const ARIAL_REGULAR_ADVANCES: Record<number, number> = {${regular.entries.join(',')}};

export const ARIAL_BOLD_ADVANCES: Record<number, number> = {${bold.entries.join(',')}};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, source);
console.log(`wrote ${OUT}: ${regular.entries.length} regular, ${bold.entries.length} bold`);
